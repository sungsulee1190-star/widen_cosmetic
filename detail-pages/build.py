def page(fn,title,body):
    html=('<!doctype html>\n<html lang="ja"><head><meta charset="utf-8">'
      '<meta name="viewport" content="width=device-width,initial-scale=1">'
      '<title>%s 詳細ページ 시안</title><link rel="stylesheet" href="style.css"></head>\n<body>\n'
      '<div class="back draft-only"><a href="index.html">&larr; 시안 목록</a></div>\n<main class="page">\n%s</main>\n</body></html>\n')%(title,body)
